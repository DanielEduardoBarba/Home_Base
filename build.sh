# ----- --run dev console (concurrently + hotkeys) -----
HOMEBASE_APPS_PID=""
HOMEBASE_EXTRA_PIDS=()
HOMEBASE_CLEANUP_DONE=false
HOTKEY_READY='r/a/w/q/h  (Ctrl+C quit)'

C_BOLD=$'\033[1m'
C_DIM=$'\033[2m'
C_CYAN=$'\033[36m'
C_GREEN=$'\033[32m'
C_YELLOW=$'\033[33m'
C_WHITE=$'\033[97m'
C_RESET=$'\033[0m'

stop_process_tree() {
  local pid="$1"
  [[ -z "$pid" ]] && return 0
  if ! kill -0 "$pid" 2>/dev/null; then
    return 0
  fi
  kill -TERM -- "-$pid" 2>/dev/null || kill -TERM "$pid" 2>/dev/null || true
  local waited=0
  while kill -0 "$pid" 2>/dev/null && [[ "$waited" -lt 20 ]]; do
    sleep 0.1
    waited=$((waited + 1))
  done
  if kill -0 "$pid" 2>/dev/null; then
    kill -KILL -- "-$pid" 2>/dev/null || kill -KILL "$pid" 2>/dev/null || true
  fi
  wait "$pid" 2>/dev/null || true
}

pids_on_port() {
  local port="$1"
  if command -v lsof >/dev/null 2>&1; then
    lsof -nP -iTCP:"$port" -sTCP:LISTEN -t 2>/dev/null || true
  elif command -v fuser >/dev/null 2>&1; then
    fuser -n tcp "$port" 2>/dev/null | tr ' ' '\n' | grep -E '^[0-9]+$' || true
  fi
}

kill_port() {
  local port="$1"
  local pid
  # Production :8888 is owned by homebased.service — never kill-by-port.
  if [[ "$port" == "$PROD_PORT" ]]; then
    echo "    refusing kill_port on :$PROD_PORT — use: systemctl stop|restart $SERVICE_NAME" >&2
    return 0
  fi
  for pid in $(pids_on_port "$port"); do
    [[ -z "$pid" ]] && continue
    stop_process_tree "$pid"
  done
}

stop_extra_pids() {
  local pid
  for pid in "${HOMEBASE_EXTRA_PIDS[@]:-}"; do
    stop_process_tree "$pid"
  done
  HOMEBASE_EXTRA_PIDS=()
}

have_controlling_tty() {
  { true </dev/tty; } 2>/dev/null
}

print_hotkey_help() {
  cat <<EOF

${C_BOLD}Dev console hotkeys:${C_RESET}
  ${C_WHITE}r${C_RESET}  restart api + web
  ${C_WHITE}a${C_RESET} / ${C_WHITE}q${C_RESET}  restart API only (Bun watch)
  ${C_WHITE}w${C_RESET}  restart web only (Next)
  ${C_WHITE}h${C_RESET}  show this help
  ${C_YELLOW}Ctrl+C${C_RESET}  quit (stop all processes)

${C_DIM}API${C_RESET}  http://localhost:${HOMEBASE_PORT:-$DEV_API_PORT}   ${C_DIM}Next${C_RESET}  http://localhost:${DEV_WEB_PORT}
EOF
}

dev_session_alive() {
  if [[ -n "${HOMEBASE_APPS_PID:-}" ]] && kill -0 "$HOMEBASE_APPS_PID" 2>/dev/null; then
    return 0
  fi
  local pid
  for pid in "${HOMEBASE_EXTRA_PIDS[@]:-}"; do
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
      return 0
    fi
  done
  return 1
}

# systemd oneshots often lack ~/.bun/bin — resolve bun into PATH when missing.
ensure_bun_on_path() {
  if command -v bun >/dev/null 2>&1; then
    return 0
  fi
  local candidate
  for candidate in \
    "${BUN_INSTALL:+$BUN_INSTALL/bin/bun}" \
    "$HOME/.bun/bin/bun" \
    /opt/homebrew/bin/bun \
    /usr/local/bin/bun \
    /usr/bin/bun; do
    if [[ -n "$candidate" && -x "$candidate" ]]; then
      export PATH="$(dirname "$candidate"):$PATH"
      return 0
    fi
  done
  return 1
}

ensure_bun_server() {
  if ! ensure_bun_on_path; then
    echo "Error: bun not found on PATH (install from https://bun.sh)" >&2
    exit 1
  fi
  local bun_dir
  bun_dir="$(bun_server_dir)"
  if [[ ! -d "$bun_dir/node_modules" ]]; then
    echo "==> Installing server deps (bun)"
    (cd "$bun_dir" && bun install)
  fi
}

api_cmd() {
  printf 'bash -lc %q' \
    "cd $(printf %q "$(bun_server_dir)") && exec bun run --watch src/entry.ts"
}

web_cmd() {
  printf 'bash -lc %q' \
    "cd $(printf %q "$ROOT/web") && exec npm run dev -- --host 0.0.0.0 --port ${DEV_WEB_PORT}"
}

ensure_concurrently() {
  if [[ ! -d web/node_modules ]]; then
    (cd web && npm install)
  fi
  if [[ ! -x web/node_modules/.bin/concurrently ]]; then
    (cd web && npm install -D concurrently)
  fi
}

spawn_concurrently_dev() {
  ensure_concurrently
  local api_sh web_sh
  api_sh="$(api_cmd)"
  web_sh="$(web_cmd)"

  # No -k: one service dying (or selective restart) must not kill siblings.
  # New session so stop_process_tree can tear down the whole group.
  if command -v setsid >/dev/null 2>&1; then
    setsid "$ROOT/web/node_modules/.bin/concurrently" \
      -n api,web -c blue,green \
      "$api_sh" \
      "$web_sh" &
  else
    "$ROOT/web/node_modules/.bin/concurrently" \
      -n api,web -c blue,green \
      "$api_sh" \
      "$web_sh" &
  fi
  HOMEBASE_APPS_PID=$!
  echo "[hotkey] stack started (pid ${HOMEBASE_APPS_PID})"
}

spawn_dev_service() {
  local name="$1"
  local cmd="$2"
  if command -v setsid >/dev/null 2>&1; then
    setsid bash -lc "echo \"[${name}] starting\"; ${cmd}" &
  else
    bash -lc "echo \"[${name}] starting\"; ${cmd}" &
  fi
  HOMEBASE_EXTRA_PIDS+=("$!")
  echo "[hotkey] ${name} started (pid $!)"
}

restart_dev_services() {
  local target="$1"
  case "$target" in
    all)
      echo "[hotkey] r → restart all (api + web)"
      if [[ -n "${HOMEBASE_APPS_PID:-}" ]]; then
        stop_process_tree "$HOMEBASE_APPS_PID"
        HOMEBASE_APPS_PID=""
      fi
      stop_extra_pids
      kill_port "${HOMEBASE_PORT:-$DEV_API_PORT}"
      kill_port "$DEV_WEB_PORT"
      spawn_concurrently_dev
      echo "[hotkey] stack restarted (pid ${HOMEBASE_APPS_PID})"
      ;;
    api)
      echo "[hotkey] → restart API only"
      kill_port "${HOMEBASE_PORT:-$DEV_API_PORT}"
      spawn_dev_service api "$(api_cmd)"
      ;;
    web)
      echo "[hotkey] w → restart web only"
      kill_port "$DEV_WEB_PORT"
      spawn_dev_service web "$(web_cmd)"
      ;;
    *)
      echo "error: unknown restart target: $target" >&2
      return 1
      ;;
  esac
}

watch_dev_hotkeys() {
  if ! have_controlling_tty; then
    wait "${HOMEBASE_APPS_PID}"
    return $?
  fi

  print_hotkey_help

  while dev_session_alive; do
    local key=""
    if ! { IFS= read -r -s -n 1 -t 1 key </dev/tty; } 2>/dev/null; then
      if ! have_controlling_tty; then
        break
      fi
      continue
    fi

    case "$key" in
      r|R)
        echo ""
        restart_dev_services all
        echo "[hotkey] ready (${HOTKEY_READY})"
        ;;
      a|A|q|Q)
        echo ""
        restart_dev_services api
        echo "[hotkey] ready (${HOTKEY_READY})"
        ;;
      w|W)
        echo ""
        restart_dev_services web
        echo "[hotkey] ready (${HOTKEY_READY})"
        ;;
      h|H|'?')
        print_hotkey_help
        ;;
    esac
  done

  wait "${HOMEBASE_APPS_PID}" 2>/dev/null || true
  return 0
}

on_session_exit() {
  if [[ "$HOMEBASE_CLEANUP_DONE" == true ]]; then
    return 0
  fi
  HOMEBASE_CLEANUP_DONE=true
  echo ""
  echo "Stopping Home Base processes (this session only)..."
  if [[ -n "${HOMEBASE_APPS_PID:-}" ]]; then
    stop_process_tree "$HOMEBASE_APPS_PID"
    HOMEBASE_APPS_PID=""
  fi
  stop_extra_pids
  kill_port "${HOMEBASE_PORT:-$DEV_API_PORT}"
  kill_port "$DEV_WEB_PORT"
}

install_session_traps() {
  trap 'on_session_exit' EXIT
  trap 'on_session_exit; exit 130' INT
  trap 'on_session_exit; exit 143' TERM
}

