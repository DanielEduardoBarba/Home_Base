# Ensure HOMEBASE_PORT exists in prod .env without overwriting a user's value.
ensure_prod_port_in_env() {
  local env_file="$1"
  [[ -f "$env_file" ]] || return 0
  if run_priv grep -qE '^HOMEBASE_PORT=' "$env_file" 2>/dev/null; then
    return 0
  fi
  run_priv bash -c "echo 'HOMEBASE_PORT=${DEFAULT_PROD_PORT}' >> $(printf %q "$env_file")"
}

# Merge selected keys from repo .env → /var/lib/homebased/.env (JWT/model/display).
# Cursor API key is in-app vault — do not require CURSOR_API_KEY in .env.
sync_env_key_from_repo() {
  local key="$1"
  local src=".env"
  local dest="$HOMEBASE_VAR/.env"
  [[ -f "$src" ]] || return 0
  [[ -f "$dest" ]] || return 0
  local val
  val="$(grep -E "^${key}=" "$src" 2>/dev/null | tail -n1 | cut -d= -f2- || true)"
  [[ -n "$val" ]] || return 0
  # Always push non-empty repo values into prod (fixes VPN Cursor when key only lived in dev .env)
  if run_priv grep -qE "^${key}=" "$dest" 2>/dev/null; then
    run_priv sed -i "s|^${key}=.*|${key}=${val}|" "$dest"
  else
    run_priv bash -c "printf '%s=%s\n' $(printf %q "$key") $(printf %q "$val") >> $(printf %q "$dest")"
  fi
  echo "    synced $key → $dest"
}

migrate_legacy_var() {
  if [[ -d "$LEGACY_VAR" ]] && [[ ! -d "$HOMEBASE_VAR" ]]; then
    echo "==> Migrating $LEGACY_VAR → $HOMEBASE_VAR"
    run_priv mv "$LEGACY_VAR" "$HOMEBASE_VAR"
  elif [[ -d "$LEGACY_VAR" ]] && [[ -d "$HOMEBASE_VAR" ]]; then
    echo "==> Removing leftover $LEGACY_VAR (already have $HOMEBASE_VAR)"
    run_priv rm -rf "$LEGACY_VAR"
  fi
}

remove_legacy_install() {
  echo "==> Removing legacy homebase.service (if present)"
  if systemctl list-unit-files "$LEGACY_SERVICE" &>/dev/null; then
    run_priv systemctl disable --now "$LEGACY_SERVICE" 2>/dev/null || true
  fi
  run_priv rm -f "/etc/systemd/system/$LEGACY_SERVICE"
  # Drop old share binary names after migrate (homebased → homebase)
  if [[ -x "$INSTALL_BIN_REAL" ]]; then
    run_priv rm -f "$LEGACY_SHARE_BIN" "$LEGACY_SHARE_BAK"
  fi
}

free_prod_port() {
  refresh_prod_port
  # Port should already be free after systemctl stop. Do not kill by port —
  # that races systemd and can occupy the listen port outside the unit.
  echo "==> Checking production port $PROD_PORT"
  local pids
  pids="$(pids_on_port "$PROD_PORT" || true)"
  if [[ -n "$pids" ]]; then
    echo "    warning: still listening on :$PROD_PORT (pids: $pids) — stop $SERVICE_NAME with systemctl" >&2
  else
    echo "    :$PROD_PORT is free"
  fi
}

prepare_var_lib() {
  migrate_legacy_var
  echo "==> Preparing $HOMEBASE_VAR"
  run_priv mkdir -p "$HOMEBASE_VAR/config" "$HOMEBASE_VAR/.runtime/logs"
  write_default_env "$ROOT/.env"
  if [[ -f "$ROOT/.env" ]] && [[ ! -f "$HOMEBASE_VAR/.env" ]]; then
    run_priv cp "$ROOT/.env" "$HOMEBASE_VAR/.env"
    echo "    copied .env → $HOMEBASE_VAR/.env"
  elif [[ ! -f "$HOMEBASE_VAR/.env" ]]; then
    # Seed prod .env the same way as the repo checkout
    local tmp
    tmp="$(mktemp)"
    rm -f "$tmp"
    write_default_env "$tmp"
    run_priv cp "$tmp" "$HOMEBASE_VAR/.env"
    rm -f "$tmp"
    run_priv chmod 600 "$HOMEBASE_VAR/.env" || true
    echo "    seeded $HOMEBASE_VAR/.env"
  fi
  if [[ -f "$HOMEBASE_VAR/.env" ]]; then
    ensure_prod_port_in_env "$HOMEBASE_VAR/.env"
    # Prefer repo HOMEBASE_PORT when the user set it (true deploy port)
    sync_env_key_from_repo "HOMEBASE_PORT"
    sync_env_key_from_repo "CURSOR_MODEL"
    sync_env_key_from_repo "HOMEBASE_JWT_SECRET"
    if [[ "$IS_LINUX" == true ]]; then
      sync_env_key_from_repo "HOMEBASE_DISPLAY"
      sync_env_key_from_repo "HOMEBASE_XAUTHORITY"
    fi
    # Optional legacy Cursor key from repo .env (prefer in-app vault)
    sync_env_key_from_repo "CURSOR_API_KEY"
    refresh_prod_port
    echo "    production HOMEBASE_PORT=$PROD_PORT (from .env)"
  fi
  # Deploy machine is source of truth for project registry
  if [[ -f "$ROOT/config/projects.json" ]]; then
    run_priv cp "$ROOT/config/projects.json" "$HOMEBASE_VAR/config/projects.json"
    echo "    synced config/projects.json → $HOMEBASE_VAR/config/"
  elif [[ ! -f "$HOMEBASE_VAR/config/projects.json" ]]; then
    run_priv cp "$ROOT/config/projects.example.json" "$HOMEBASE_VAR/config/projects.json"
    echo "    seeded config/projects.json from example"
  fi
  # Keep Run + Expo as compose (two PTYs) even on older prod projects.json
  if [[ -f "$HOMEBASE_VAR/config/projects.json" ]]; then
    run_priv python3 - <<'PY' || echo "    warning: compose upgrade skipped" >&2
import json
from pathlib import Path
path = Path("/var/lib/homebased/config/projects.json")
data = json.loads(path.read_text())
compose = {
    "id": "run_all",
    "label": "Run + Expo",
    "type": "compose",
    "compose": ["run", "expo"],
    "variant": "accent",
    "group": "main",
}
changed = False
for p in data.get("projects") or []:
    actions = p.get("actions") or []
    for i, a in enumerate(actions):
        if a.get("id") == "run_all" and (
            a.get("type") != "compose" or a.get("compose") != ["run", "expo"]
        ):
            actions[i] = {**a, **compose}
            changed = True
    p["actions"] = actions
if changed:
    path.write_text(json.dumps(data, indent=2) + "\n")
    print("    upgraded run_all → compose (run + expo)")
PY
  fi
  secure_var_ownership
}

# Set after we stop the unit so EXIT trap can bring it back if deploy aborts.
HOMEBASED_UNIT_STOPPED=0
INSTALL_USED_BACKUP=0

ensure_homebased_running_on_exit() {
  if [[ "${HOMEBASED_UNIT_STOPPED}" != "1" ]]; then
    return 0
  fi
  echo "==> Deploy interrupted — starting $SERVICE_NAME again" >&2
  if run_priv systemctl start "$SERVICE_NAME" \
    || run_priv systemctl restart "$SERVICE_NAME"; then
    return 0
  fi
  echo "    error: systemctl could not start $SERVICE_NAME — run: systemctl start $SERVICE_NAME" >&2
  return 1
}

stop_homebased() {
  # Must stop before replacing binaries — Linux returns ETXTBSY ("Text file busy")
  # when cp overwrites an executable that is still mapped/running.
  # Unit TimeoutStopSec=20; let systemd stop (and SIGKILL the cgroup) — no pkill.
  if ! systemctl list-unit-files "$SERVICE_NAME" &>/dev/null; then
    return 0
  fi
  echo "==> Stopping $SERVICE_NAME (systemctl)"
  # timeout must wrap the real binary, not the run_priv bash function.
  # 35s > TimeoutStopSec so systemd can finish its own stop sequence.
  if ! run_priv timeout 35 systemctl stop "$SERVICE_NAME"; then
    echo "Error: systemctl stop $SERVICE_NAME failed — approve polkit/sudo and retry" >&2
    echo "    do not kill homebase by hand; use: systemctl stop $SERVICE_NAME" >&2
    exit 1
  fi
  HOMEBASED_UNIT_STOPPED=1
  if systemctl list-unit-files "$LEGACY_SERVICE" &>/dev/null; then
    run_priv timeout 30 systemctl stop "$LEGACY_SERVICE" 2>/dev/null || true
  fi
  # Wait briefly for the listen socket to drop (systemd already stopped the unit).
  local waited=0
  while ss -ltn 2>/dev/null | grep -qE ":${PROD_PORT}[[:space:]]"; do
    if [[ "$waited" -ge 30 ]]; then
      echo "    warning: :$PROD_PORT still listening after systemctl stop" >&2
      break
    fi
    sleep 0.1
    waited=$((waited + 1))
  done
}

# Install unit file, enable, restart, and verify active + :8888.
# Always the last step of --deploy / --service — never skip.
restart_homebased_service() {
  echo "==> Restarting $SERVICE_NAME"
  run_priv cp "$SERVICE_SRC" "$SERVICE_DST"
  run_priv timeout 15 systemctl daemon-reload || true
  run_priv timeout 15 systemctl enable "$SERVICE_NAME" || true
  run_priv timeout 10 systemctl reset-failed "$SERVICE_NAME" 2>/dev/null || true

  # If somehow still inside the unit cgroup, never call systemctl restart in-process.
  if under_homebased_service; then
    if ! schedule_detached_restart; then
      return 1
    fi
    HOMEBASED_UNIT_STOPPED=0
    echo "==> Detached restart scheduled (skip sync wait — this process may die)"
    return 0
  fi

  if ! run_priv timeout 35 systemctl restart "$SERVICE_NAME"; then
    echo "Error: systemctl restart $SERVICE_NAME failed" >&2
    run_priv timeout 5 systemctl --no-pager --full status "$SERVICE_NAME" >&2 || true
    run_priv timeout 5 journalctl -u "$SERVICE_NAME" -n 40 --no-pager >&2 || true
    return 1
  fi
  local i
  for i in $(seq 1 40); do
    if run_priv timeout 3 systemctl is-active --quiet "$SERVICE_NAME" 2>/dev/null; then
      break
    fi
    sleep 0.25
  done
  HOMEBASED_UNIT_STOPPED=0
  run_priv timeout 5 systemctl --no-pager --full status "$SERVICE_NAME" || true
  if ! run_priv timeout 3 systemctl is-active --quiet "$SERVICE_NAME" 2>/dev/null; then
    echo "Error: $SERVICE_NAME is not active after restart" >&2
    run_priv timeout 5 journalctl -u "$SERVICE_NAME" -n 40 --no-pager >&2 || true
    return 1
  fi
  if wait_for_listen "$PROD_PORT"; then
    echo "==> $SERVICE_NAME active — http://localhost:${PROD_PORT}/"
  else
    echo "Error: nothing listening on :$PROD_PORT after restart" >&2
    run_priv timeout 5 journalctl -u "$SERVICE_NAME" -n 40 --no-pager >&2 || true
    return 1
  fi
  echo "==> Service $SERVICE_NAME enabled and restarted"
  echo "    HOMEBASE_HOME=$HOMEBASE_VAR  binary=$INSTALL_BIN → $INSTALL_BIN_REAL  port=$PROD_PORT"
  return 0
}

install_binary() {
  if [[ ! -x "$BIN_PATH" ]]; then
    echo "Error: missing binary $BIN_PATH — run ./build.sh --bin first" >&2
    exit 1
  fi
  if [[ ! -f "$WRAPPER_SRC" ]]; then
    echo "Error: missing wrapper $WRAPPER_SRC" >&2
    exit 1
  fi
  # Root builds leave root-owned dist/; reclaim so cp source is readable and next
  # non-root build can overwrite. Install targets are always root:root below.
  claim_dist_to_workspace
  echo "==> Safe install → $INSTALL_BIN_REAL (+ wrapper $INSTALL_WRAPPER / $SERVICE_NAME)"
  stop_homebased
  run_priv mkdir -p "$INSTALL_SHARE"
  run_priv chown root:root "$INSTALL_SHARE"
  run_priv chmod 755 "$INSTALL_SHARE"

  # Rename share binary homebased → homebase (keep .bak continuity)
  if [[ ! -x "$INSTALL_BIN_REAL" ]] && [[ -x "$LEGACY_SHARE_BIN" ]]; then
    echo "    migrating $LEGACY_SHARE_BIN → $INSTALL_BIN_REAL"
    run_priv mv -f "$LEGACY_SHARE_BIN" "$INSTALL_BIN_REAL"
  fi
  if [[ ! -x "$INSTALL_BIN_BAK" ]] && [[ -x "$LEGACY_SHARE_BAK" ]]; then
    echo "    migrating $LEGACY_SHARE_BAK → $INSTALL_BIN_BAK"
    run_priv mv -f "$LEGACY_SHARE_BAK" "$INSTALL_BIN_BAK"
  fi

  # Migrate fat binary formerly at /usr/bin/homebase(d) into the share layout once
  for candidate in "$LEGACY_WRAPPER" "$INSTALL_WRAPPER"; do
    if [[ ! -x "$INSTALL_BIN_REAL" ]] && [[ -x "$candidate" ]]; then
      if ! head -n1 "$candidate" 2>/dev/null | grep -qE 'bash|sh'; then
        echo "    migrating fat $candidate → $INSTALL_BIN_REAL"
        run_priv cp -f "$candidate" "$INSTALL_BIN_REAL"
        run_priv chmod 755 "$INSTALL_BIN_REAL"
        break
      fi
    fi
  done

  local ver="0.0.0" prev_ver=""
  if [[ -f "$VERSION_FILE" ]]; then
    ver="$(head -n1 "$VERSION_FILE" | tr -d '[:space:]')"
  fi
  if [[ -f "$INSTALL_SHARE/VERSION" ]]; then
    prev_ver="$(run_priv head -n1 "$INSTALL_SHARE/VERSION" 2>/dev/null | tr -d '[:space:]' || true)"
  fi

  # Always park the currently deployed primary as .bak, then put the new build in place.
  # (Do not call this twice in one deploy — that would bak the new binary over the old.)
  if [[ -x "$INSTALL_BIN_REAL" ]]; then
    echo "    previous → .bak${prev_ver:+ (v${prev_ver})}"
    run_priv cp -f "$INSTALL_BIN_REAL" "$INSTALL_BIN_BAK"
    run_priv chmod 755 "$INSTALL_BIN_BAK"
    if [[ -f "$INSTALL_SHARE/VERSION" ]]; then
      run_priv cp -f "$INSTALL_SHARE/VERSION" "$INSTALL_SHARE/VERSION.bak"
    fi
  else
    echo "    no previous binary — first install (no .bak yet)"
  fi

  # Atomic install of new binary as primary
  run_priv cp "$BIN_PATH" "${INSTALL_BIN_REAL}.new"
  run_priv chmod 755 "${INSTALL_BIN_REAL}.new"
  run_priv mv -f "${INSTALL_BIN_REAL}.new" "$INSTALL_BIN_REAL"
  run_priv cp "$VERSION_FILE" "$INSTALL_SHARE/VERSION" 2>/dev/null || \
    run_priv bash -c "printf '%s\n' $(printf %q "$ver") > $(printf %q "$INSTALL_SHARE/VERSION")"
  run_priv rm -f "$INSTALL_SHARE/.running-backup"

  # Bun compile does not embed SPA — install web/dist + presets beside the binary.
  if [[ -d "$BIN_OUT_DIR/web/dist" ]]; then
    echo "    installing SPA → $INSTALL_SHARE/web/dist"
    run_priv mkdir -p "$INSTALL_SHARE/web"
    run_priv rm -rf "$INSTALL_SHARE/web/dist"
    run_priv cp -a "$BIN_OUT_DIR/web/dist" "$INSTALL_SHARE/web/dist"
  elif [[ -d "$ROOT/web/dist" ]]; then
    echo "    installing SPA from repo → $INSTALL_SHARE/web/dist"
    run_priv mkdir -p "$INSTALL_SHARE/web"
    run_priv rm -rf "$INSTALL_SHARE/web/dist"
    run_priv cp -a "$ROOT/web/dist" "$INSTALL_SHARE/web/dist"
  fi
  if [[ -d "$ROOT/config/presets" ]]; then
    run_priv mkdir -p "$INSTALL_SHARE/config"
    run_priv rm -rf "$INSTALL_SHARE/config/presets"
    run_priv cp -a "$ROOT/config/presets" "$INSTALL_SHARE/config/presets"
  fi

  # Install / refresh wrapper at /usr/bin/homebase; drop old /usr/bin/homebased name
  run_priv cp "$WRAPPER_SRC" "${INSTALL_WRAPPER}.new"
  run_priv chmod 755 "${INSTALL_WRAPPER}.new"
  run_priv mv -f "${INSTALL_WRAPPER}.new" "$INSTALL_WRAPPER"
  if [[ -e "$LEGACY_WRAPPER" ]]; then
    echo "    removing legacy wrapper $LEGACY_WRAPPER"
    run_priv rm -f "$LEGACY_WRAPPER"
  fi

  secure_install_ownership

  # Probe new primary; if it fails, restore .bak so systemd can still start.
  # Never exit here — caller must still restart homebased.service.
  INSTALL_USED_BACKUP=0
  if ! probe_bin "$INSTALL_BIN_REAL"; then
    echo "    NEW binary failed self-test" >&2
    tmp="$(mktemp -d /tmp/homebased-probe.XXXXXX)"
    TMPDIR="$tmp" HOMEBASE_SELF_TEST=1 HOMEBASE_HOME="$tmp" HOMEBASE_RUNTIME="$tmp/.runtime" \
      "$INSTALL_BIN_REAL" 2>&1 | tail -n 5 || \
      run_priv env TMPDIR="$tmp" HOMEBASE_SELF_TEST=1 HOMEBASE_HOME="$tmp" \
        HOMEBASE_RUNTIME="$tmp/.runtime" "$INSTALL_BIN_REAL" 2>&1 | tail -n 5 || true
    rm -rf "$tmp" 2>/dev/null || true
    if [[ -x "$INSTALL_BIN_BAK" ]]; then
      echo "    restoring .bak as active binary" >&2
      run_priv cp -f "$INSTALL_BIN_BAK" "$INSTALL_BIN_REAL"
      if [[ -f "$INSTALL_SHARE/VERSION.bak" ]]; then
        run_priv cp -f "$INSTALL_SHARE/VERSION.bak" "$INSTALL_SHARE/VERSION"
      fi
      run_priv bash -c "echo 1 > $(printf %q "$INSTALL_SHARE/.running-backup")"
      secure_install_ownership
      INSTALL_USED_BACKUP=1
    else
      echo "    warning: no .bak — primary may be broken; will still try to start service" >&2
      INSTALL_USED_BACKUP=1
    fi
  else
    echo "    primary v${ver} (previous${prev_ver:+ v${prev_ver}} kept as .bak)"
  fi
}

port_is_listening() {
  local port="$1"
  if command -v ss >/dev/null 2>&1; then
    ss -tln 2>/dev/null | grep -F ":${port}" >/dev/null
    return $?
  fi
  if command -v lsof >/dev/null 2>&1; then
    lsof -nP -iTCP:"$port" -sTCP:LISTEN >/dev/null 2>&1
    return $?
  fi
  return 1
}

wait_for_listen() {
  local port="$1"
  local i
  for i in $(seq 1 40); do
    if port_is_listening "$port"; then
      return 0
    fi
    sleep 0.25
  done
  return 1
}
cmd_service_linux() {
  echo "==> Installing $SERVICE_NAME"
  if [[ ! -f "$SERVICE_SRC" ]]; then
    echo "Error: missing $SERVICE_SRC" >&2
    exit 1
  fi
  ensure_priv_session "homebased service install"
  trap '_stop_sudo_keepalive; ensure_homebased_running_on_exit' EXIT

  INSTALL_USED_BACKUP=0
  if [[ -x "$BIN_PATH" ]]; then
    # Refresh share binary + wrapper from dist (once per deploy/service)
    install_binary
  elif [[ ! -x "$INSTALL_BIN_REAL" ]] && [[ ! -x "$INSTALL_WRAPPER" ]]; then
    echo "Error: no binary at $BIN_PATH or $INSTALL_BIN_REAL — run ./build.sh --bin or ./build.sh --deploy" >&2
    exit 1
  else
    echo "    using existing install at $INSTALL_BIN_REAL (no new dist/ binary)"
  fi

  remove_legacy_install
  free_prod_port
  prepare_var_lib
  if [[ -f "$ROOT/scripts/hb-hook-approve" ]]; then
    echo "==> Installing approval hook → $INSTALL_SHARE/hb-hook-approve"
    run_priv install -m 0755 "$ROOT/scripts/hb-hook-approve" "$INSTALL_SHARE/hb-hook-approve"
  fi
  if [[ -f "$ROOT/scripts/hb-vpn-access.sh" ]]; then
    echo "==> Installing VPN access helper → $INSTALL_SHARE/hb-vpn-access.sh"
    run_priv install -m 0755 "$ROOT/scripts/hb-vpn-access.sh" "$INSTALL_SHARE/hb-vpn-access.sh"
    # Unit already has ExecStartPre; legacy drop-in doubled UFW apply (~8s per start).
    if [[ -f /etc/systemd/system/homebased.service.d/vpn-access.conf ]]; then
      echo "==> Removing duplicate vpn-access.conf ExecStartPre drop-in"
      run_priv rm -f /etc/systemd/system/homebased.service.d/vpn-access.conf
      run_priv systemctl daemon-reload
    fi
  fi

  if ! restart_homebased_service; then
    exit 1
  fi
  trap - EXIT

  if [[ "${INSTALL_USED_BACKUP:-0}" == "1" ]] || [[ -f "$INSTALL_SHARE/.running-backup" ]]; then
    echo "    WARNING: running BACKUP binary — new build failed self-test; fix and redeploy" >&2
    exit 1
  fi
}

# True when this shell is inside homebased.service's cgroup (Chat PTY / agent).
under_homebased_service() {
  [[ "${HOMEBASE_DETACHED_DEPLOY:-}" == "1" || "$FROM_DETACHED" == true ]] && return 1
  [[ -r /proc/self/cgroup ]] || return 1
  grep -qE 'homebased\.service' /proc/self/cgroup 2>/dev/null
}

# Schedule deploy outside homebased's KillMode=control-group so stop/restart
# cannot abort the job mid-flight (chat-driven ./build.sh --deploy).
schedule_detached_deploy() {
  echo "==> Detected deploy inside homebased — scheduling detached systemd oneshot"
  ensure_priv_session "homebased detached deploy"
  ensure_bun_on_path || true
  local unit="homebased-self-deploy-$(date +%s%N)"
  local cmd
  # Carry PATH (incl. ~/.bun/bin) so the oneshot can find bun/node.
  cmd="cd $(printf %q "$ROOT") && export HOMEBASE_DETACHED_DEPLOY=1 PATH=$(printf %q "$PATH") && exec ./build.sh --deploy --from-detached"
  # --no-block: return immediately so Chat/agent isn't killed when homebased restarts.
  if ! run_priv systemd-run \
      --no-block \
      --unit="$unit" \
      --property=Type=oneshot \
      --property=TimeoutStartSec=900 \
      --working-directory="$ROOT" \
      /bin/bash -lc "$cmd"; then
    echo "Error: systemd-run failed to schedule detached deploy" >&2
    exit 1
  fi
  echo "==> Detached deploy started as unit: $unit"
  echo "    Logs: journalctl -u $unit -f"
  echo "    Home Base will stop/restart shortly; this Chat/Shell session may disconnect."
  echo "    When back: curl -s http://127.0.0.1:${PROD_PORT}/api/version"
}

# Restart via transient timer outside this process tree (safe from inside the unit).
schedule_detached_restart() {
  local timer="homebased-self-restart-$(date +%s%N)"
  echo "==> Scheduling detached restart ($timer)"
  if ! run_priv systemd-run \
      --collect \
      --unit="$timer" \
      --on-active=1s \
      --timer-property=AccuracySec=100ms \
      systemctl restart "$SERVICE_NAME"; then
    echo "Error: systemd-run failed to schedule restart" >&2
    return 1
  fi
  echo "    restart scheduled — unit will come back in ~1s"
  return 0
}

cmd_deploy() {
  require_linux "Deploy / systemd install" || exit 1
  # Chat/agent self-deploy: never stop homebased from inside its own cgroup.
  if under_homebased_service; then
    schedule_detached_deploy
    return 0
  fi

  echo "==> Deploy: build → install homebase binary → restart homebased.service"
  # Elevate before bin so reclaiming root-owned dist/web paths only prompts once.
  ensure_priv_session "homebased deploy"
  cmd_bin
  # install_binary runs once inside cmd_service (avoid double-install, which
  # would copy the NEW primary over .bak and lose the real previous binary)
  cmd_service
  seed_homebase_project || true
  echo "==> Deploy complete → http://0.0.0.0:${PROD_PORT}/ ($SERVICE_NAME)"
}

cmd_service() {
  require_linux "Service install" || exit 1
  cmd_service_linux
}

