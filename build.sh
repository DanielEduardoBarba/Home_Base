# Always rebuild SPA (deploy / --bin must ship current UI, not a stale web/dist).
build_web_dist() {
  echo "==> Building web UI"
  if [[ ! -d web/node_modules ]]; then
    (cd web && npm install)
  fi
  # Prior sudo builds can leave root-owned web/dist; move it aside so Next can write.
  if [[ -d web/dist ]] && [[ ! -w web/dist || ( -d web/dist/_next && ! -w web/dist/_next ) ]]; then
    local stamped="web/dist.unwritable.$(date +%s)"
    echo "    web/dist not writable — moving aside → $stamped"
    mv web/dist "$stamped" 2>/dev/null \
      || run_priv mv web/dist "$stamped" \
      || {
        echo "Error: cannot replace root-owned web/dist (try: sudo chown -R \"\$USER:\$USER\" web/dist)" >&2
        exit 1
      }
  fi
  # Cap worker threads under memory pressure so deploy still works on a busy laptop.
  (
    cd web
    export UV_THREADPOOL_SIZE="${UV_THREADPOOL_SIZE:-2}"
    npm run build
  )
}

# Soft sudo for --clean (do not abort the whole clean if the user skips the password).
try_priv_for_clean() {
  if [[ "${PRIV_MODE}" == "root" || "${PRIV_MODE}" == "sudo" || "$(id -u)" -eq 0 ]]; then
    [[ "$(id -u)" -eq 0 ]] && PRIV_MODE="root"
    return 0
  fi
  if ! command -v sudo >/dev/null 2>&1; then
    return 1
  fi
  if sudo -n true 2>/dev/null; then
    PRIV_MODE="sudo"
    return 0
  fi
  if [[ ! -t 0 ]]; then
    return 1
  fi
  echo "==> Elevating once for homebased clean (single sudo password; cached for this run)"
  if sudo -v; then
    PRIV_MODE="sudo"
    (
      while true; do
        sleep 50
        sudo -n true 2>/dev/null || exit 0
      done
    ) &
    _SUDO_KEEPALIVE_PID=$!
    return 0
  fi
  return 1
}

# Remove path if present. Elevates once if root-owned leftovers block rm.
clean_rm() {
  local p="$1"
  local elevate="${2:-auto}" # auto | priv
  if [[ ! -e "$p" && ! -L "$p" ]]; then
    return 0
  fi
  if [[ "$elevate" != "priv" ]]; then
    if rm -rf "$p" 2>/dev/null; then
      echo "  removed $p"
      return 0
    fi
  fi
  if try_priv_for_clean && run_priv rm -rf "$p"; then
    echo "  removed $p"
    return 0
  fi
  echo "  warn: could not remove $p (re-run: sudo ./build.sh --clean)" >&2
  return 1
}

cmd_clean() {
  echo "==> Clean: Python/Nuitka leftovers, local runtime, setup/build caches"
  echo "    (keeps .env and config/projects.json)"
  local warned=0

  # Legacy Python API tree + tooling
  clean_rm "$ROOT/.venv" || warned=1
  clean_rm "$ROOT/venv" || warned=1
  clean_rm "$ROOT/server-py" || warned=1
  clean_rm "$ROOT/homebase_entry.py" || warned=1
  clean_rm "$ROOT/requirements.txt" || warned=1
  clean_rm "$ROOT/requirements-dev.txt" || warned=1
  clean_rm "$ROOT/.pytest_cache" || warned=1
  clean_rm "$ROOT/.mypy_cache" || warned=1
  clean_rm "$ROOT/nuitka-crash-report.xml" || warned=1
  clean_rm "$ROOT/homebase.build" || warned=1
  clean_rm "$ROOT/homebase.dist" || warned=1
  clean_rm "$ROOT/homebase.onefile-build" || warned=1
  clean_rm "$ROOT/dist.oldroot" || warned=1
  # Old pytest suite lived at repo-root tests/ (Bun tests are server/test/)
  if [[ -d "$ROOT/tests" ]] && [[ -f "$ROOT/tests/conftest.py" || -f "$ROOT/tests/test_auth.py" ]]; then
    clean_rm "$ROOT/tests" || warned=1
  fi

  # Nested Python caches under the repo (skip node_modules / .git)
  while IFS= read -r -d '' d; do
    clean_rm "$d" || warned=1
  done < <(find "$ROOT" \
    \( -path "$ROOT/.git" -o -path "$ROOT/web/node_modules" -o -path "$ROOT/server/node_modules" \) -prune \
    -o \( -type d \( -name '__pycache__' -o -name '*.egg-info' \) -print0 \) 2>/dev/null)

  # Local runtime + regenerable setup/build outputs
  clean_rm "$ROOT/.runtime" || warned=1
  clean_rm "$ROOT/dist" || warned=1
  clean_rm "$ROOT/web/dist" || warned=1
  clean_rm "$ROOT/web/out" || warned=1
  clean_rm "$ROOT/web/.next" || warned=1
  clean_rm "$ROOT/web/tsconfig.tsbuildinfo" || warned=1
  clean_rm "$ROOT/server/node_modules" || warned=1
  clean_rm "$ROOT/web/node_modules" || warned=1

  # Installed leftovers from the Python/Nuitka era
  clean_rm "$LEGACY_VAR" priv || warned=1
  clean_rm "$INSTALL_SHARE/cursor-sdk-bridge" priv || warned=1
  if compgen -G "/tmp/onefile_*" >/dev/null 2>&1; then
    for d in /tmp/onefile_*; do
      clean_rm "$d" priv || warned=1
    done
  fi

  if [[ "$warned" -ne 0 ]]; then
    echo "==> Clean finished with leftovers (sudo needed for some paths)."
  else
    echo "==> Clean complete. Run ./build.sh --setup to restore deps."
  fi
}

cmd_setup() {
  echo "==> Bun server deps"
  ensure_bun_server

  echo "==> Frontend deps"
  if [[ ! -d web/node_modules || ! -x web/node_modules/.bin/next ]]; then
    (cd web && npm install) || {
      echo "Error: npm install failed in web/" >&2
      exit 1
    }
  else
    # Refresh is best-effort — never abort onboarding when deps already work
    # (npm --silent can exit non-zero / 243 on some hosts while leaving a fine tree).
    if ! (cd web && npm install --no-fund --no-audit >/dev/null 2>&1); then
      echo "    web deps already present — continuing"
    fi
  fi

  mkdir -p config .runtime/logs dist
  if [[ ! -f config/projects.json ]]; then
    cp config/projects.example.json config/projects.json
    echo "==> Created empty config/projects.json"
  fi

  write_default_env "$ROOT/.env"
  echo "==> .env ready"

  # Pin checkout paths so an installed prod share cannot steal HOME / JWT writes.
  export HOMEBASE_HOME="${HOMEBASE_HOME:-$ROOT}"
  export HOMEBASE_BUNDLE_ROOT="${HOMEBASE_BUNDLE_ROOT:-$ROOT}"
  export HOMEBASE_RUNTIME="${HOMEBASE_RUNTIME:-$ROOT/.runtime}"

  # Ensure JWT signing material exists (password is set later via localhost UI)
  (
    cd "$(bun_server_dir)"
    bun -e 'import { jwtSecret } from "./src/auth.ts"; jwtSecret(); console.log("JWT secret ready")'
  )

  # Drop legacy HOMEBASE_TOKEN from .env if present (auth is password → JWT now)
  if grep -qE '^HOMEBASE_TOKEN=' .env 2>/dev/null; then
    sed_inplace '/^HOMEBASE_TOKEN=/d' .env
    echo "Removed legacy HOMEBASE_TOKEN from .env"
  fi

  seed_homebase_project

  echo ""
  echo "Setup complete."
  echo "  Open UI on localhost → create a password (only localhost can set/change it)."
  echo "  Home Base project is ready — open Chat to vibe-code this repo."
  echo "  Add more apps in the UI (+ in Apps) or: ./build.sh --add-project --path /path/to/repo"
  echo "  Dev console:   ./build.sh --run"
  echo "  Full install:  ./build.sh --onboarding"
}

# Idempotent: register this checkout as the Home Base project.
seed_homebase_project() {
  echo "==> Seeding Home Base project (this repo)"
  mkdir -p config
  if [[ ! -f config/projects.json ]]; then
    cp config/projects.example.json config/projects.json
  fi
  ensure_bun_server
  export HOMEBASE_HOME="${HOMEBASE_HOME:-$ROOT}"
