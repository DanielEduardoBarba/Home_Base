# Read HOMEBASE_PORT from a .env file (first match), else default.
read_homebase_port() {
  local env_file="${1:-}"
  local raw=""
  if [[ -n "$env_file" && -f "$env_file" ]]; then
    raw="$(grep -E '^HOMEBASE_PORT=' "$env_file" 2>/dev/null | tail -n1 | cut -d= -f2- | tr -d '"' | tr -d "'" | tr -d ' ' || true)"
  fi
  if [[ -z "$raw" && -f "$ROOT/.env" ]]; then
    raw="$(grep -E '^HOMEBASE_PORT=' "$ROOT/.env" 2>/dev/null | tail -n1 | cut -d= -f2- | tr -d '"' | tr -d "'" | tr -d ' ' || true)"
  fi
  if [[ "$raw" =~ ^[0-9]+$ ]] && [[ "$raw" -ge 1 && "$raw" -le 65535 ]]; then
    echo "$raw"
  else
    echo "$DEFAULT_PROD_PORT"
  fi
}

# Refresh PROD_PORT from repo or prod .env (call before deploy/service checks).
refresh_prod_port() {
  if [[ -f "$HOMEBASE_VAR/.env" ]]; then
    PROD_PORT="$(read_homebase_port "$HOMEBASE_VAR/.env")"
  else
    PROD_PORT="$(read_homebase_port "$ROOT/.env")"
  fi
}

# Create .env when missing: from .env.example, no CURSOR_API_KEY; View vars on Linux only.
write_default_env() {
  local dest="${1:-$ROOT/.env}"
  if [[ -f "$dest" ]]; then
    return 0
  fi
  echo "==> Creating $dest (from defaults · no Cursor key)"
  local seat_user seat_home xauth
  seat_user="${SUDO_USER:-$(id -un)}"
  if [[ "$seat_user" == "root" ]]; then
    seat_home="/root"
  else
    seat_home="$(getent passwd "$seat_user" 2>/dev/null | cut -d: -f6 || echo "/home/$seat_user")"
  fi
  xauth="${seat_home}/.Xauthority"

  {
    echo "# Home Base — generated by ./build.sh --setup / --onboarding"
    echo "# Cursor API key: set in the app (encrypted). Do not put CURSOR_API_KEY here."
    echo ""
    echo "HOMEBASE_HOST=0.0.0.0"
    echo "HOMEBASE_PORT=${DEFAULT_PROD_PORT}"
    echo "CURSOR_MODEL=auto"
    if [[ "$IS_LINUX" == true ]]; then
      echo ""
      echo "# View (X11) — Linux only"
      echo "HOMEBASE_DISPLAY=:0"
      echo "HOMEBASE_XAUTHORITY=${xauth}"
    fi
  } > "$dest"
  chmod 600 "$dest" 2>/dev/null || true
}

