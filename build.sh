# Portable helpers (GNU + BSD / macOS)
sed_inplace() {
  local expr="$1" file="$2"
  if [[ "$OS_NAME" == "Darwin" ]]; then
    sed -i '' "$expr" "$file"
  else
    sed -i "$expr" "$file"
  fi
}

stat_owner() {
  local path="$1"
  if [[ "$OS_NAME" == "Darwin" ]]; then
    stat -f '%Su' "$path" 2>/dev/null || echo ""
  else
    stat -c '%U' "$path" 2>/dev/null || echo ""
  fi
}

lan_ip_guess() {
  if command -v ip >/dev/null 2>&1; then
    ip -4 -o addr show scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -1
    return 0
  fi
  if command -v ifconfig >/dev/null 2>&1; then
    ifconfig 2>/dev/null | awk '/inet / && $2 != "127.0.0.1" { print $2; exit }'
    return 0
  fi
  hostname -I 2>/dev/null | awk '{print $1}' || true
}

